export function buildPrompt(shot: TeamShot): string {
  return `${SCENE_PROMPT} Shot ${shot.id}, ${shot.kind}, "${shot.title}": ${shot.prompt}`;
}

export function shotFiles(id: string): { file: string; fileSm: string } {
  return { file: `/team/group-${id}.webp`, fileSm: `/team/group-${id}-sm.webp` };
}

/** Parse `--only 04` / `--only 4` into a shot id; null when the flag is absent. */
export function normalizeOnly(v: string | undefined): string | null {
  if (v === undefined) return null;
  const n = Number(v);
  if (!Number.isInteger(n) || n < 1 || n > TEAM_SHOTS.length) throw new Error(`--only must be 1..${TEAM_SHOTS.length}, got "${v}"`);
  return String(n).padStart(2, "0");
}

export interface ManifestEntry {
  id: string; file: string; fileSm: string; kind: "formal" | "candid";
  title: string; alt: string; caption: string; generatedAt: string; model: string;
}

